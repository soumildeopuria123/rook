/**
 * Turns a player's tournament games into an opening book.
 *
 *   bun scripts/build-player-books.ts carlsen="Carlsen,Magnus"=/tmp/games/Carlsen.pgn \
 *     sindarov="Sindarov,Javokhir"=/tmp/twic/twic*.pgn
 *
 * Every game is replayed, the first sixteen plies are recorded as a line, and
 * identical lines are counted. The output is a frequency table of the openings
 * that player actually plays with each colour, which the app then follows. No
 * full game is stored or shipped.
 */
import { Chess } from 'chess.js'
import { readFileSync, writeFileSync } from 'node:fs'

const PLIES = 16
const LINES_PER_COLOUR = 90
const MIN_YEAR = 2016

type Spec = { key: string; player: string; minYear: number; files: string[] }
type Line = [string, number]

// The fourth field is optional: a retired player's games all matter, while an
// active one should be represented by how they open now.
const specs: Spec[] = process.argv.slice(2).map((argument) => {
  const [key, player, files, year] = argument.split('=')
  return {
    key,
    player,
    minYear: Number(year) || MIN_YEAR,
    files: files.split(','),
  }
})
if (!specs.length) {
  console.error(
    'usage: bun scripts/build-player-books.ts key="Surname,Name"=file.pgn[,file.pgn][=minYear]',
  )
  process.exit(1)
}

const strip = (text: string) => {
  let body = text
  for (let i = 0; i < 3; i++) body = body.replace(/\([^()]*\)/g, ' ')
  return body
    .replace(/\{[^}]*\}/g, ' ')
    .replace(/;[^\n]*/g, ' ')
    .replace(/\$\d+/g, ' ')
    .replace(/\d+\s*\.(\.\.)?/g, ' ')
    .replace(/\b(1-0|0-1|1\/2-1\/2|\*)\b/g, ' ')
    .replace(/[?!]+/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
}

/** The first PLIES moves as coordinate notation, or null if the game is unusable. */
function opening(movetext: string): string[] | null {
  const tokens = strip(movetext)
  if (tokens.length < PLIES) return null
  const chess = new Chess()
  const line: string[] = []
  for (const token of tokens) {
    if (line.length >= PLIES) break
    let move
    try {
      move = chess.move(token)
    } catch {
      return line.length >= PLIES ? line : null
    }
    if (!move) return null
    line.push(`${move.from}${move.to}${move.promotion ?? ''}`)
  }
  return line.length === PLIES ? line : null
}

function readGames(
  file: string,
  minYear: number,
): { white: string; black: string; year: number; pgn: string }[] {
  let text: string
  try {
    // Collections are distributed with CRLF line endings; headers and movetext
    // are separated by a blank line either way.
    text = readFileSync(file, 'latin1').replace(/\r\n?/g, '\n')
  } catch {
    return []
  }
  return text
    .split(/(?=\[Event )/)
    .map((chunk) => {
      const tag = (name: string) =>
        new RegExp(`\\[${name} "([^"]*)"\\]`).exec(chunk)?.[1] ?? ''
      const date = tag('Date')
      const pgn = chunk.split(/\n\n/).slice(1).join('\n\n')
      return {
        white: tag('White'),
        black: tag('Black'),
        year: Number(date.slice(0, 4)) || 0,
        pgn,
      }
    })
    .filter((game) => game.pgn && game.year >= minYear)
}

const output: Record<string, { w: Line[]; b: Line[] }> = {}
for (const spec of specs) {
  const counts: Record<'w' | 'b', Map<string, number>> = {
    w: new Map(),
    b: new Map(),
  }
  let played = 0
  for (const file of spec.files) {
    for (const game of readGames(file, spec.minYear)) {
      // "Tal,Mikhail" must not also match a player whose first name contains it.
      const surname = new RegExp(
        `^${spec.player.split(',')[0].trim()}(?=[,\\s])`,
        'i',
      )
      const colour = surname.test(game.white)
        ? 'w'
        : surname.test(game.black)
          ? 'b'
          : null
      if (!colour) continue
      const line = opening(game.pgn)
      if (!line) continue
      played += 1
      const key = line.join(' ')
      counts[colour].set(key, (counts[colour].get(key) ?? 0) + 1)
    }
  }
  const top = (map: Map<string, number>): Line[] =>
    [...map.entries()]
      .sort((a, b) => b[1] - a[1])
      .slice(0, LINES_PER_COLOUR)
      .map(([line, count]) => [line, count] as Line)
  output[spec.key] = { w: top(counts.w), b: top(counts.b) }
  console.error(
    `${spec.key}: ${played} games, ${output[spec.key].w.length} white lines, ${output[spec.key].b.length} black lines`,
  )
}

const body = Object.entries(output)
  .map(([key, book]) => {
    const lines = (entries: Line[]) =>
      entries.map(([line, count]) => `    ['${line}', ${count}],`).join('\n')
    return `  ${key}: {\n    w: [\n${lines(book.w)}\n    ],\n    b: [\n${lines(book.b)}\n    ],\n  },`
  })
  .join('\n')

writeFileSync(
  'src/shared/player-book-data.ts',
  `// Generated by scripts/build-player-books.ts from public tournament games.
// Each entry is an opening line in coordinate notation and how many of the
// player's games reached it. Do not edit by hand.

export type BookLine = readonly [line: string, count: number]

export const PLAYER_BOOK_LINES: Record<
  string,
  { w: readonly BookLine[]; b: readonly BookLine[] }
> = {
${body}
}
`,
)
console.error('wrote src/shared/player-book-data.ts')
